mod blot;
mod model;
mod rust;
use anyhow::{Context, Result, bail};
use std::path::Path;

pub const SCHEMA: &str = include_str!("../../../protocol/schema.json");
const HEADER: &str = "Generated by pen codegen from pen/protocol/schema.json:\nedit the schema and run `pen codegen`, not this file.";

pub fn generate(project: &Path, rust_output: Option<&Path>, check: bool) -> Result<()> {
    let model =
        model::build(serde_json::from_str(SCHEMA).context("invalid protocol/schema.json")?)?;
    let rust = rust::emit(&model, HEADER);
    let mut outputs: Vec<_> = blot::emit(&model, HEADER)
        .into_iter()
        .map(|(name, source)| (project.join("pen").join(name), source))
        .collect();
    if let Some(path) = rust_output {
        outputs.push((path.to_owned(), rust));
    }
    let mut stale = Vec::new();
    for (path, contents) in &outputs {
        if std::fs::read_to_string(path).ok().as_ref() == Some(contents) {
            continue;
        }
        if check {
            stale.push(path.display().to_string());
        } else {
            if let Some(parent) = path.parent() {
                std::fs::create_dir_all(parent)
                    .with_context(|| format!("create {}", parent.display()))?;
            }
            std::fs::write(path, contents).with_context(|| format!("write {}", path.display()))?;
        }
    }
    if !stale.is_empty() {
        bail!(
            "stale generated protocol; run pen codegen:\n{}",
            stale.join("\n")
        );
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::Value;

    fn schema() -> Value {
        serde_json::from_str(SCHEMA).unwrap()
    }

    #[test]
    fn packet_contract_layout() {
        let model = model::build(schema()).unwrap();
        assert_eq!(model.magic, 0x474446);
        assert_eq!(model.header_lanes, 138);
        assert_eq!(model.event_lanes(), 5);
        assert_eq!(model.section("draws").fixed.as_ref().unwrap().lanes, 24);
        assert_eq!(model.section("insets").fixed.as_ref().unwrap().lanes, 47);
        assert_eq!(model.section("ui").head_lanes, 24);
    }

    #[test]
    fn blot_bindings_own_their_nominal_types() {
        let model = model::build(schema()).unwrap();
        assert!(!SCHEMA.contains("\"blot\""));
        let sources = blot::emit(&model, HEADER);
        for (_, source) in &sources {
            for import in source.lines().filter(|line| line.starts_with("import ")) {
                let path = import.split('"').nth(1).unwrap();
                assert!(
                    ["std/array", "./lanes", "./protocol", "./types"].contains(&path),
                    "external binding dependency: {path}"
                );
            }
        }
        let render = &sources
            .iter()
            .find(|(name, _)| *name == "protocol_render.blot")
            .unwrap()
            .1;
        assert!(render.contains("fn (packet: types.RenderFrame)"));
        assert!(render.contains("fn (draw: types.Draw)"));
        assert!(render.contains("draw.transform"));
        assert!(render.contains("inset.ambient.x"));
        assert!(render.contains("packet.clear.r"));
        assert!(render.contains("packet.clouds.drift.z"));
        let types = &sources
            .iter()
            .find(|(name, _)| *name == "types.blot")
            .unwrap()
            .1;
        assert!(types.contains("transform: Mat4"));
        assert!(types.contains("parameters: Maybe Vec4"));
        assert!(types.contains("draws: Array Draw"));
        assert!(types.contains("state: Array F32"));
    }

    #[test]
    fn malformed_relationships_are_rejected() {
        let mut invalid = schema();
        invalid["render"]["sections"][0]["name"] = Value::String("unknown".into());
        assert!(model::build(invalid).is_err());
        let mut invalid = schema();
        invalid["input"]["events"][1]["tag"] = invalid["input"]["events"][0]["tag"].clone();
        assert!(model::build(invalid).is_err());
        let mut invalid = schema();
        invalid["input"]["events"][0]["value"]["lane"] = Value::String("missing".into());
        assert!(model::build(invalid).is_err());
        let mut invalid = schema();
        invalid["render"]["header"]["quality.msaa"]["kind"] = Value::String("unknown".into());
        assert!(model::build(invalid).is_err());
        let mut invalid = schema();
        invalid["render"]["sections"]
            .as_array_mut()
            .unwrap()
            .reverse();
        assert!(model::build(invalid).is_err());
    }

    #[test]
    fn malformed_shapes_return_errors_without_panics() {
        fn visit(value: &Value, path: String, paths: &mut Vec<String>) {
            paths.push(path.clone());
            if let Some(object) = value.as_object() {
                for (key, child) in object {
                    visit(child, format!("{path}/{key}"), paths);
                }
            }
            if let Some(array) = value.as_array() {
                for (index, child) in array.iter().enumerate() {
                    visit(child, format!("{path}/{index}"), paths);
                }
            }
        }
        let original = schema();
        let mut paths = Vec::new();
        visit(&original, String::new(), &mut paths);
        for path in paths {
            for replacement in [Value::Null, Value::Bool(false)] {
                let mut invalid = original.clone();
                *invalid.pointer_mut(&path).unwrap() = replacement;
                let result = std::panic::catch_unwind(|| {
                    if let Ok(model) = model::build(invalid) {
                        rust::emit(&model, HEADER);
                        blot::emit(&model, HEADER);
                    }
                });
                assert!(result.is_ok(), "malformed schema panicked at {path}");
            }
        }
    }

    #[test]
    fn freshness_check_detects_edits_and_missing_outputs() {
        let dir = std::env::temp_dir().join(format!("pen-codegen-test-{}", std::process::id()));
        let rust = dir.join("packets.rs");
        generate(&dir, Some(&rust), false).unwrap();
        generate(&dir, Some(&rust), true).unwrap();
        std::fs::write(&rust, "stale").unwrap();
        assert!(generate(&dir, Some(&rust), true).is_err());
        assert_eq!(std::fs::read_to_string(&rust).unwrap(), "stale");
        std::fs::remove_file(dir.join("pen/types.blot")).unwrap();
        assert!(generate(&dir, None, true).is_err());
        generate(&dir, Some(&rust), false).unwrap();
        generate(&dir, Some(&rust), true).unwrap();
        std::fs::remove_dir_all(&dir).unwrap();
    }
}
